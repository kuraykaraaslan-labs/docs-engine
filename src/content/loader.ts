import fs from 'node:fs';
import path from 'node:path';
import { parse as parseYaml } from 'yaml';
import { z } from 'zod';
import { getCollection, type CollectionConfig, type DocsConfig } from '../config/schema';
import { parseFrontmatter } from './frontmatter';
import { autogenerate, flattenSidebar, prettify, resolveSidebar, stripNumberPrefix, type SidebarSource } from './sidebar';
import type { CategoryMeta, DocLink, DocRecord, DocsCollection } from './types';

export type LoadOptions = {
  /** Site root that collection `dir`s are relative to. Default process.cwd(). */
  rootDir?: string;
  /** Include `draft: true` docs. Default: only outside production. */
  includeDrafts?: boolean;
};

const categorySchema = z
  .object({
    label: z.string().optional(),
    position: z.number().optional(),
    collapsed: z.boolean().optional(),
    collapsible: z.boolean().optional(),
    link: z.union([z.string(), z.object({ type: z.literal('doc'), id: z.string() })]).optional(),
  })
  .passthrough();

const CATEGORY_FILES = ['_category_.json', '_category_.yml', '_category_.yaml'];
const LEADING_H1 = /^\s*#[ \t]+(.+?)[ \t]*#*[ \t]*(?:\r?\n|$)/;

function readCategory(dirAbs: string): CategoryMeta | undefined {
  for (const name of CATEGORY_FILES) {
    const file = path.join(/*turbopackIgnore: true*/ dirAbs, name);
    if (!fs.existsSync(file)) continue;
    const text = fs.readFileSync(file, 'utf8');
    const raw = name.endsWith('.json') ? JSON.parse(text) : parseYaml(text);
    const parsed = categorySchema.safeParse(raw ?? {});
    if (!parsed.success) throw new Error(`${file}: ${parsed.error.issues.map((i) => i.message).join('; ')}`);
    const { link, ...rest } = parsed.data;
    return { ...rest, link: typeof link === 'string' ? link : link?.id };
  }
  return undefined;
}

function joinHref(...parts: string[]): string {
  const joined = parts.filter(Boolean).join('/').replace(/\/+/g, '/').replace(/^\/|\/$/g, '');
  return `/${joined}`;
}

function walk(dirAbs: string, relDir: string, out: { file: string; rel: string }[], dirs: string[]) {
  for (const entry of fs.readdirSync(dirAbs, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    if (entry.name.startsWith('.') || entry.name.startsWith('_')) continue;
    const rel = relDir ? `${relDir}/${entry.name}` : entry.name;
    const abs = path.join(/*turbopackIgnore: true*/ dirAbs, entry.name);
    if (entry.isDirectory()) {
      dirs.push(rel);
      walk(abs, rel, out, dirs);
    } else if (entry.isFile() && entry.name.endsWith('.md')) {
      out.push({ file: abs, rel });
    }
  }
}

function buildDoc(collection: CollectionConfig, absPath: string, rel: string): DocRecord {
  const raw = fs.readFileSync(absPath, 'utf8');
  const { data, body: afterFrontmatter } = parseFrontmatter(raw, absPath);

  const segments = rel.replace(/\.md$/, '').split('/');
  const stripped = segments.map((s) => stripNumberPrefix(s));
  const fileName = stripped[stripped.length - 1];
  const dir = stripped.slice(0, -1).map((s) => s.name).join('/');
  const baseName = data.id ?? fileName.name;
  const id = dir ? `${dir}/${baseName}` : baseName;
  const isIndex = /^(index|readme)$/i.test(fileName.name);

  let slug: string;
  if (data.slug !== undefined) slug = data.slug.startsWith('/') ? data.slug.replace(/^\/+|\/+$/g, '') : [dir, data.slug].filter(Boolean).join('/');
  else slug = isIndex ? dir : id;

  let body = afterFrontmatter;
  let h1: string | undefined;
  const m = LEADING_H1.exec(body);
  if (m) {
    h1 = m[1];
    body = body.slice(m[0].length);
  }
  const title = data.title ?? h1 ?? prettify(isIndex ? dir.split('/').pop() || collection.id : fileName.name);

  return {
    id,
    collection: collection.id,
    filePath: rel,
    absPath,
    slug,
    href: joinHref(collection.routeBasePath, slug),
    title,
    description: data.description,
    sidebarLabel: data.sidebar_label ?? title,
    sidebarPosition: data.sidebar_position ?? fileName.position,
    dir,
    isIndex,
    draft: data.draft === true,
    frontmatter: data,
    body,
  };
}

// Per config object, then per root/collection/drafts: two configs never share a sidebar.
const cache = new WeakMap<DocsConfig, Map<string, DocsCollection>>();

/**
 * Reads one collection: every .md file under its `dir` (folders and files
 * starting with `_` or `.` are skipped), its `_category_.json` files, and the
 * sidebar from docs.config.ts or, when the collection names none, one
 * autogenerated from the folder tree. Cached per process outside development.
 */
export function loadCollection(config: DocsConfig, collectionId: string, options: LoadOptions = {}): DocsCollection {
  const rootDir = options.rootDir ?? process.cwd();
  const includeDrafts = options.includeDrafts ?? process.env.NODE_ENV !== 'production';
  const key = `${rootDir}\0${collectionId}\0${includeDrafts}`;
  const cacheable = process.env.NODE_ENV !== 'development';
  let perConfig = cache.get(config);
  if (!perConfig) cache.set(config, (perConfig = new Map()));
  const hit = cacheable ? perConfig.get(key) : undefined;
  if (hit) return hit;

  const collection = getCollection(config, collectionId);
  // turbopackIgnore: content is read at build time (every page is prerendered), so there
  // is nothing for the server bundle's file tracing to include.
  const dirAbs = path.resolve(/*turbopackIgnore: true*/ rootDir, collection.dir);
  if (!fs.existsSync(dirAbs)) throw new Error(`docs collection "${collection.id}": folder not found: ${dirAbs}`);

  const files: { file: string; rel: string }[] = [];
  const dirs: string[] = [];
  walk(dirAbs, '', files, dirs);

  const docs = files.map((f) => buildDoc(collection, f.file, f.rel)).filter((d) => includeDrafts || !d.draft);

  const byId = new Map<string, DocRecord>();
  const bySlug = new Map<string, DocRecord>();
  for (const doc of docs) {
    const sameId = byId.get(doc.id);
    if (sameId) throw new Error(`docs collection "${collection.id}": duplicate doc id "${doc.id}" (${sameId.filePath}, ${doc.filePath})`);
    const sameSlug = bySlug.get(doc.slug);
    if (sameSlug) throw new Error(`docs collection "${collection.id}": duplicate URL ${doc.href} (${sameSlug.filePath}, ${doc.filePath})`);
    byId.set(doc.id, doc);
    bySlug.set(doc.slug, doc);
  }

  const categories = new Map<string, CategoryMeta>();
  const rawDirNames = new Map<string, string>();
  for (const rel of dirs) {
    const idDir = rel.split('/').map((s) => stripNumberPrefix(s).name).join('/');
    rawDirNames.set(idDir, rel.split('/').pop()!);
    const meta = readCategory(path.join(/*turbopackIgnore: true*/ dirAbs, rel));
    if (meta) categories.set(idDir, meta);
  }

  const src: SidebarSource = { docs, byId, categories, rawDirNames };
  const sidebar = collection.sidebar
    ? resolveSidebar(src, config.sidebars[collection.sidebar], collection.sidebar)
    : autogenerate(src, '');

  const result: DocsCollection = { config: collection, docs, byId, bySlug, categories, sidebar, order: flattenSidebar(sidebar) };
  if (cacheable) perConfig.set(key, result);
  return result;
}

/** The doc at a catch-all route's segments (`[]` = the collection's root page). */
export function getDocBySlug(collection: DocsCollection, segments: string[] | undefined): DocRecord | undefined {
  return collection.bySlug.get((segments ?? []).map(decodeURIComponent).join('/'));
}

/** Previous / next page in sidebar order, overridable per doc with `pagination_prev` / `pagination_next`. */
export function getDocNeighbors(collection: DocsCollection, doc: DocRecord): { prev: DocLink | null; next: DocLink | null } {
  const link = (id: string | null | undefined): DocLink | null => {
    if (!id) return null;
    const d = collection.byId.get(id);
    return d ? { title: d.sidebarLabel, href: d.href } : null;
  };
  const i = collection.order.indexOf(doc.id);
  const fm = doc.frontmatter;
  const prev = fm.pagination_prev !== undefined ? link(fm.pagination_prev) : i > 0 ? link(collection.order[i - 1]) : null;
  const next = fm.pagination_next !== undefined ? link(fm.pagination_next) : i !== -1 ? link(collection.order[i + 1]) : null;
  return { prev, next };
}

/** `generateStaticParams` rows for a `[[...slug]]` route. */
export function collectionStaticParams(collection: DocsCollection): { slug: string[] }[] {
  return collection.docs.map((d) => ({ slug: d.slug ? d.slug.split('/') : [] }));
}
