import path from 'node:path';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { defineDocsConfig } from '../config/schema';
import { loadCollection, getDocBySlug, getDocNeighbors, collectionStaticParams } from './loader';
import type { SidebarNode } from './types';

const rootDir = path.join(import.meta.dirname, '..', '__fixtures__', 'site');
const config = defineDocsConfig({
  site: { title: 'Fixture', url: 'https://example.com' },
  collections: [{ id: 'docs', dir: 'docs', routeBasePath: 'docs' }],
});

const shape = (nodes: SidebarNode[]): unknown =>
  nodes.map((n) => (n.type === 'category' ? { cat: n.label, href: n.href, collapsed: n.collapsed, items: shape(n.items) } : n.label));

describe('loadCollection', () => {
  afterEach(() => vi.unstubAllEnvs());

  it('derives ids, slugs and titles from paths, number prefixes, frontmatter and the leading H1', () => {
    const col = loadCollection(config, 'docs', { rootDir, includeDrafts: false });
    const install = col.byId.get('getting-started/install')!;
    expect(install.title).toBe('Installation');
    expect(install.href).toBe('/docs/getting-started/install');
    expect(install.body).not.toMatch(/^# Installation/);
    expect(install.sidebarPosition).toBe(1);

    expect(col.byId.get('index')!.href).toBe('/docs');
    expect(col.byId.get('guides/index')!.href).toBe('/docs/guides');
    expect(col.byId.get('guides/writing')!.href).toBe('/docs/how-to-write');
    expect(col.byId.get('getting-started/configure')!.sidebarLabel).toBe('Configure');
  });

  it('skips _-prefixed folders and, when asked, drafts', () => {
    const col = loadCollection(config, 'docs', { rootDir, includeDrafts: false });
    expect(col.docs.some((d) => d.filePath.startsWith('_private'))).toBe(false);
    expect(col.byId.has('guides/theming')).toBe(false);
    expect(loadCollection(config, 'docs', { rootDir, includeDrafts: true }).byId.has('guides/theming')).toBe(true);
  });

  it('autogenerates the sidebar from folders, _category_ files and positions', () => {
    const col = loadCollection(config, 'docs', { rootDir, includeDrafts: false });
    expect(shape(col.sidebar)).toEqual([
      'Welcome',
      { cat: 'Getting Started', href: undefined, collapsed: false, items: ['Installation', 'Configure'] },
      {
        cat: 'Guides',
        href: '/docs/guides',
        collapsed: true,
        items: ['Writing pages', { cat: 'Advanced topics', href: undefined, collapsed: true, items: ['Fence plugins'] }],
      },
    ]);
    expect(col.order).toEqual([
      'index',
      'getting-started/install',
      'getting-started/configure',
      'guides/index',
      'guides/writing',
      'guides/advanced/plugins',
    ]);
  });

  it('resolves a manual sidebar and rejects unknown doc ids', () => {
    const manual = defineDocsConfig({
      site: { title: 'Fixture', url: 'https://example.com' },
      collections: [{ id: 'docs', dir: 'docs', sidebar: 'main' }],
      sidebars: {
        main: [
          'index',
          { type: 'category', label: 'Start', link: 'guides/index', items: [{ type: 'autogenerated', dir: 'getting-started' }] },
          { type: 'link', label: 'GitHub', href: 'https://github.com' },
        ],
      },
    });
    const col = loadCollection(manual, 'docs', { rootDir, includeDrafts: false });
    expect(shape(col.sidebar)).toEqual([
      'Welcome',
      { cat: 'Start', href: '/docs/guides', collapsed: true, items: ['Installation', 'Configure'] },
      'GitHub',
    ]);
    expect(col.sidebar[2]).toMatchObject({ type: 'link', external: true });

    const broken = defineDocsConfig({ ...manual, sidebars: { main: ['nope'] } });
    expect(() => loadCollection(broken, 'docs', { rootDir, includeDrafts: false })).toThrow(/no doc with id "nope"/);
  });

  it('finds docs by route segments and walks prev/next in sidebar order', () => {
    const col = loadCollection(config, 'docs', { rootDir, includeDrafts: false });
    expect(getDocBySlug(col, undefined)!.id).toBe('index');
    const configure = getDocBySlug(col, ['getting-started', 'configure'])!;
    expect(getDocNeighbors(col, configure)).toEqual({
      prev: { title: 'Installation', href: '/docs/getting-started/install' },
      next: { title: 'Guides', href: '/docs/guides' },
    });
    expect(collectionStaticParams(col)).toContainEqual({ slug: [] });
    expect(collectionStaticParams(col)).toContainEqual({ slug: ['how-to-write'] });
  });
});
