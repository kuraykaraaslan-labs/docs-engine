import type { SidebarItemInput } from '../config/schema';
import { isExternalHref } from '../config/schema';
import type { CategoryMeta, DocRecord, SidebarNode } from './types';

export type SidebarSource = {
  docs: DocRecord[];
  byId: Map<string, DocRecord>;
  categories: Map<string, CategoryMeta>;
  /** Folder id -> folder name as authored (with its number prefix), for ordering. */
  rawDirNames: Map<string, string>;
};

const natural = new Intl.Collator(undefined, { numeric: true, sensitivity: 'base' });

export function prettify(segment: string): string {
  const words = segment.replace(/[-_]+/g, ' ').trim();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

/** Leading "01-" / "1_" / "1." on a path segment: the position, and the name without it. */
export function stripNumberPrefix(segment: string): { name: string; position?: number } {
  const m = /^(\d+)[-_.]\s*(.+)$/.exec(segment);
  return m ? { name: m[2], position: Number(m[1]) } : { name: segment };
}

function parentDir(dir: string): string {
  const i = dir.lastIndexOf('/');
  return i === -1 ? '' : dir.slice(0, i);
}

function docNode(doc: DocRecord, label?: string): SidebarNode {
  return { type: 'doc', id: doc.id, label: label ?? doc.sidebarLabel, href: doc.href };
}

function categoryIndexDoc(src: SidebarSource, dir: string): DocRecord | undefined {
  const linkId = src.categories.get(dir)?.link;
  if (linkId) return src.byId.get(linkId);
  return src.docs.find((d) => d.dir === dir && d.isIndex);
}

/**
 * One sidebar level from the folder tree: the docs directly inside `dir` plus a
 * category per subfolder, ordered by position (frontmatter `sidebar_position`,
 * `_category_.json` `position`, else the number prefix of the file or folder
 * name), then by name. A subfolder's index.md (or its `_category_.json` `link`)
 * becomes the category's own page instead of a child entry.
 */
export function autogenerate(src: SidebarSource, dir: string, nested = false): SidebarNode[] {
  type Entry = { position: number; sortName: string; node: SidebarNode };
  const entries: Entry[] = [];
  const childDirs = new Set<string>();

  for (const doc of src.docs) {
    if (doc.dir === dir) {
      // Inside a category, the folder's landing page is the category link, not a child.
      if (nested && doc.isIndex && categoryIndexDoc(src, dir)?.id === doc.id) continue;
      entries.push({
        position: doc.sidebarPosition ?? (doc.isIndex ? -Infinity : Infinity),
        sortName: doc.filePath,
        node: docNode(doc),
      });
    } else if (dir === '' || doc.dir.startsWith(`${dir}/`)) {
      // The immediate child folder of `dir` on the way to this doc.
      let child = doc.dir;
      while (parentDir(child) !== dir) child = parentDir(child);
      childDirs.add(child);
    }
  }

  for (const child of childDirs) {
    const meta = src.categories.get(child) ?? {};
    const raw = src.rawDirNames.get(child) ?? child.split('/').pop()!;
    const { name, position } = stripNumberPrefix(raw);
    const index = categoryIndexDoc(src, child);
    entries.push({
      position: meta.position ?? position ?? Infinity,
      sortName: raw,
      node: {
        type: 'category',
        key: child,
        label: meta.label ?? (index?.frontmatter.sidebar_label as string | undefined) ?? prettify(name),
        items: autogenerate(src, child, true),
        collapsed: meta.collapsed ?? true,
        collapsible: meta.collapsible ?? true,
        href: index?.href,
        docId: index?.id,
      },
    });
  }

  entries.sort((a, b) => a.position - b.position || natural.compare(a.sortName, b.sortName));
  return entries.map((e) => e.node);
}

/** Resolves a sidebar from docs.config.ts into nodes. An unknown doc id fails loudly: it is a broken link. */
export function resolveSidebar(src: SidebarSource, items: SidebarItemInput[], sidebarName: string): SidebarNode[] {
  const out: SidebarNode[] = [];
  for (const item of items) {
    if (typeof item === 'string' || item.type === 'doc') {
      const id = typeof item === 'string' ? item : item.id;
      const doc = src.byId.get(id);
      if (!doc) throw new Error(`sidebar "${sidebarName}": no doc with id "${id}"`);
      out.push(docNode(doc, typeof item === 'string' ? undefined : item.label));
    } else if (item.type === 'link') {
      out.push({ type: 'link', label: item.label, href: item.href, external: isExternalHref(item) });
    } else if (item.type === 'autogenerated') {
      out.push(...autogenerate(src, item.dir.replace(/^\/+|\/+$/g, '')));
    } else {
      const linked = item.link ? src.byId.get(item.link) : undefined;
      if (item.link && !linked) throw new Error(`sidebar "${sidebarName}": category "${item.label}" links to unknown doc "${item.link}"`);
      out.push({
        type: 'category',
        key: `${sidebarName}:${item.label}`,
        label: item.label,
        items: resolveSidebar(src, item.items, sidebarName),
        collapsed: item.collapsed ?? true,
        collapsible: item.collapsible ?? true,
        href: linked?.href,
        docId: linked?.id,
      });
    }
  }
  return out;
}

/** Doc ids in reading order: a category's own page first, then its children. */
export function flattenSidebar(nodes: SidebarNode[]): string[] {
  const ids: string[] = [];
  const walk = (list: SidebarNode[]) => {
    for (const node of list) {
      if (node.type === 'doc') ids.push(node.id);
      else if (node.type === 'category') {
        if (node.docId) ids.push(node.docId);
        walk(node.items);
      }
    }
  };
  walk(nodes);
  return [...new Set(ids)];
}

/** True when `href` is this node or anywhere under it — used to expand the active branch. */
export function containsHref(node: SidebarNode, href: string): boolean {
  if (node.type === 'category') return node.href === href || node.items.some((n) => containsHref(n, href));
  return node.href === href;
}
