import { z } from 'zod';

// docs.config.ts — the one file a site author edits to shape the chrome:
// site identity, navbar, footer, sidebars and the content collections they
// navigate. Everything here is data (no React), so the same config is read by
// Server Components, generateStaticParams and build scripts alike.

const href = z.string().min(1);

export const navLinkSchema = z
  .object({
    label: z.string().min(1),
    href,
    /** Opens in a new tab with rel="noopener noreferrer". Defaults to true for absolute http(s) URLs. */
    external: z.boolean().optional(),
  })
  .strict();

const navbarLinkSchema = navLinkSchema
  .extend({
    type: z.literal('link').optional(),
    position: z.enum(['left', 'right']).default('left'),
    /** CSS-order style position inside its side: missing counts as 0, ties keep array order. */
    order: z.number().optional(),
  })
  .strict();

const navbarSlotSchema = z
  .object({
    type: z.literal('slot'),
    /** Name of a node the host passes to DocsShell's `navbarSlots` — search boxes, user menus and the like. */
    name: z.string().min(1),
    position: z.enum(['left', 'right']).default('right'),
    order: z.number().optional(),
  })
  .strict();

export const navbarItemSchema = z.union([navbarLinkSchema, navbarSlotSchema]);

export type SidebarItemInput =
  | string
  | { type: 'doc'; id: string; label?: string }
  | { type: 'link'; label: string; href: string }
  | { type: 'category'; label: string; items: SidebarItemInput[]; collapsed?: boolean; collapsible?: boolean; link?: string }
  | { type: 'autogenerated'; dir: string };

export const sidebarItemSchema: z.ZodType<SidebarItemInput> = z.lazy(() =>
  z.union([
    z.string().min(1),
    z.object({ type: z.literal('doc'), id: z.string().min(1), label: z.string().optional() }).strict(),
    z.object({ type: z.literal('link'), label: z.string().min(1), href }).strict(),
    z
      .object({
        type: z.literal('category'),
        label: z.string().min(1),
        items: z.array(sidebarItemSchema),
        collapsed: z.boolean().optional(),
        collapsible: z.boolean().optional(),
        /** Doc id the category label itself links to. */
        link: z.string().optional(),
      })
      .strict(),
    z.object({ type: z.literal('autogenerated'), dir: z.string() }).strict(),
  ])
);

export const collectionSchema = z
  .object({
    id: z.string().regex(/^[a-z0-9-]+$/, 'collection id: lowercase letters, digits and dashes'),
    /** Folder of .md files, relative to the site root. */
    dir: z.string().min(1),
    /** URL prefix, without slashes. '' mounts the collection at the site root. */
    routeBasePath: z.string().regex(/^[a-z0-9-/]*$/).default('docs'),
    /** Key into `sidebars`. Omitted = one sidebar autogenerated from the whole folder. */
    sidebar: z.string().optional(),
    /** Base URL of an "Edit this page" link; the doc's path inside `dir` is appended. */
    editUrl: z.string().url().optional(),
  })
  .strict();

export const docsConfigSchema = z
  .object({
    site: z
      .object({
        title: z.string().min(1),
        tagline: z.string().optional(),
        description: z.string().optional(),
        /** Absolute origin, used for metadataBase and canonical URLs. */
        url: z.string().url(),
        /** <html lang>. */
        locale: z.string().default('en'),
        logo: z
          .object({
            /** Image under /public. Omitted = text-only wordmark (or the host's own `logo` node). */
            src: z.string().optional(),
            alt: z.string().optional(),
            text: z.string().optional(),
            href: z.string().default('/'),
          })
          .strict()
          .optional(),
      })
      .strict(),
    navbar: z
      .object({
        items: z.array(navbarItemSchema).default([]),
        /** Show the light/dark toggle at the far right. */
        themeToggle: z.boolean().default(true),
      })
      .strict()
      .default({}),
    footer: z
      .object({
        links: z.array(navLinkSchema).default([]),
        copyright: z.string().optional(),
        version: z.string().optional(),
      })
      .strict()
      .optional(),
    /** Markdown collections. Empty for a host that uses only the shell and the pipeline. */
    collections: z.array(collectionSchema).default([]),
    sidebars: z.record(z.array(sidebarItemSchema)).default({}),
    toc: z
      .object({
        minDepth: z.number().int().min(1).max(6).default(2),
        maxDepth: z.number().int().min(1).max(6).default(3),
      })
      .strict()
      .default({}),
    theme: z
      .object({
        defaultMode: z.enum(['system', 'light', 'dark']).default('system'),
      })
      .strict()
      .default({}),
  })
  .strict()
  .superRefine((config, ctx) => {
    const ids = new Set<string>();
    config.collections.forEach((c, i) => {
      if (ids.has(c.id)) ctx.addIssue({ code: 'custom', path: ['collections', i, 'id'], message: `duplicate collection id "${c.id}"` });
      ids.add(c.id);
      if (c.sidebar && !(c.sidebar in config.sidebars)) {
        ctx.addIssue({ code: 'custom', path: ['collections', i, 'sidebar'], message: `sidebar "${c.sidebar}" is not defined in sidebars` });
      }
    });
  });

export type DocsConfigInput = z.input<typeof docsConfigSchema>;
export type DocsConfig = z.output<typeof docsConfigSchema>;
export type NavLink = z.output<typeof navLinkSchema>;
export type NavbarItem = z.output<typeof navbarItemSchema>;
export type CollectionConfig = z.output<typeof collectionSchema>;

/**
 * Validates and normalizes a docs config. Throws a readable error listing every
 * problem, so a typo in docs.config.ts fails the build rather than a page.
 */
export function defineDocsConfig(input: DocsConfigInput): DocsConfig {
  const result = docsConfigSchema.safeParse(input);
  if (!result.success) {
    const lines = result.error.issues.map((i) => `  - ${i.path.join('.') || '(root)'}: ${i.message}`);
    throw new Error(`Invalid docs config:\n${lines.join('\n')}`);
  }
  return result.data;
}

export function getCollection(config: DocsConfig, id: string): CollectionConfig {
  const collection = config.collections.find((c) => c.id === id);
  if (!collection) throw new Error(`Unknown docs collection "${id}" (have: ${config.collections.map((c) => c.id).join(', ')})`);
  return collection;
}

export function isExternalHref(link: { href: string; external?: boolean }): boolean {
  return link.external ?? /^https?:\/\//.test(link.href);
}
